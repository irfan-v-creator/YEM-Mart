export function lookupKeralaDistrict(pincode: string): KeralaDistrict | null {
  if (!pincode || pincode.length < 3) return null;
  const prefix = pincode.slice(0, 3);
  return KERALA_DISTRICTS[prefix] || null;
}

export function isKeralaPincode(pincode: string): boolean {
  if (!pincode || pincode.length !== 6) return false;
  // Official Kerala postal circle pincodes begin with 67, 68, or 69
  return /^(67|68|69)\d{4}$/.test(pincode);
}

